"""Frozen prompts. Their sha256 hashes go into every run manifest; change the version when the text changes.

None of these prompts may contain gold facts, rubric criteria or hints about the expected cause.
"""

from __future__ import annotations

import hashlib

PROMPT_VERSION = "v1"

TASK = (
    "Investigate why checkout requests became slow after the latest release. Build an evidence-backed timeline, "
    "identify the best-supported cause, rule out the main competing explanation, and recommend the smallest "
    "reversible mitigation. Do not modify production settings or disable payment safety checks."
)

AGENT_SYSTEM = """You are an on-call engineer doing a read-only incident investigation.
You can only inspect a fixed evidence bundle through three tools: list_artifacts, search_artifacts and read_artifact. You cannot change, deploy or roll back anything.

How to work:
- Decide for yourself what to inspect. Check claims against the artifacts; do not infer causality from timing alone.
- Cite evidence for factual claims as [artifact-id:L<line>] or [artifact-id:L<first>-L<last>], using the line numbers shown by the tools.
- Earlier parts of this conversation may be replaced by a summary when the context grows. Artifacts can always be read again.

When you have finished, reply without any tool call, using exactly these sections:
## Timeline
## Best-supported cause
## Competing explanation
## Recommended mitigation
## Uncertainty"""

SUMMARY_SYSTEM = """You compress the earlier part of an incident investigation so that the investigation can continue in a smaller context window.
You do not know the answer to the investigation. Do not guess it, and do not add facts that are not in the material you are given."""

SUMMARY_USER = """Original task:
{task}

Previous summary (from an earlier compaction; empty if none):
{previous}

Transcript of the earlier investigation steps that are being removed from the context:
{transcript}

Write a continuation summary for the investigator who will continue this work. Preserve:
1. The task and its constraints.
2. Evidence gathered so far: concrete values (timestamps, durations, counts, configuration values) copied exactly, each with its reference in the form [artifact-id:L<first>-L<last>].
3. Findings so far: hypotheses considered and what supports or contradicts each, with references.
4. Unresolved questions and the next steps that were planned.
5. Which artifacts and line ranges were already read, so they can be read again if needed.
Mark uncertain points as uncertain. Use plain text and stay under about {max_words} words."""

FOCUSED_USER = """{task}

The evidence excerpts you need are attached below; tools are not available in this condition. Line numbers are the artifacts' own line numbers, so cite them as [artifact-id:L<line>].

{excerpts}"""

SUMMARY_MESSAGE_PREFIX = "[Context summary"


def summary_message(n: int, replaced: int, text: str) -> str:
    return (f"{SUMMARY_MESSAGE_PREFIX} #{n}: generated by automatic compaction; it replaces {replaced} earlier "
            f"messages. Artifacts can be read again.]\n\n{text}")


def prompt_hashes() -> dict[str, str]:
    return {name: hashlib.sha256(text.encode("utf-8")).hexdigest()
            for name, text in (("TASK", TASK), ("AGENT_SYSTEM", AGENT_SYSTEM), ("SUMMARY_SYSTEM", SUMMARY_SYSTEM),
                               ("SUMMARY_USER", SUMMARY_USER), ("FOCUSED_USER", FOCUSED_USER))}
